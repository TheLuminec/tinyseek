"""Generate the Arduino sketches' copies of the shared firmware sources.

    python -m tinyseek.deploy.arduino_sketch          # rewrite the copies in every sketch
    python -m tinyseek.deploy.arduino_sketch --check  # exit 1 if any copy is stale

The ESP-IDF project (firmware/perf_eval) is the single source of truth for the shared
code: the platform shim, the camera and JPEG decoding, and the portable tinyseek_core.
The Arduino IDE compiles only files inside the sketch folder and symlinks do not survive
on Windows, so each sketch's src/ holds verbatim copies, each behind a "generated" banner.
Build differences live in the sources behind ``#ifdef ARDUINO``.

Two sketches use them:

- firmware/perf_eval_arduino: the on-device evaluation (its own logic is a copy of
  perf_eval's main/perf_eval.*);
- firmware/detector: the live detector (its own logic is hand-written in that folder).

Everything else in a sketch folder is listed in its ``hand_written`` set.
tests/test_deploy_arduino_sketch.py fails when a copy drifts from its source.
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
IDF = Path("firmware/perf_eval")
CORE = IDF / "components/tinyseek_core"

# Shared by every sketch: sketch path -> source path, both relative to the repository root.
SHARED: dict[str, str] = {
    "src/platform.hpp": str(IDF / "main/platform.hpp"),
    "src/platform.cpp": str(IDF / "main/platform.cpp"),
    "src/camera.hpp": str(IDF / "main/camera.hpp"),
    "src/camera.cpp": str(IDF / "main/camera.cpp"),
    "src/board_pins.h": "firmware/capture/board_pins.h",
    "src/tinyseek_core/preprocess.hpp": str(CORE / "include/tinyseek_core/preprocess.hpp"),
    "src/tinyseek_core/decode.hpp": str(CORE / "include/tinyseek_core/decode.hpp"),
    "src/tinyseek_core/jpeg_info.hpp": str(CORE / "include/tinyseek_core/jpeg_info.hpp"),
    "src/tinyseek_core/kv.hpp": str(CORE / "include/tinyseek_core/kv.hpp"),
    "src/preprocess.cpp": str(CORE / "src/preprocess.cpp"),
    "src/decode.cpp": str(CORE / "src/decode.cpp"),
    "src/jpeg_info.cpp": str(CORE / "src/jpeg_info.cpp"),
    "src/kv.cpp": str(CORE / "src/kv.cpp"),
}


@dataclass(frozen=True)
class Sketch:
    path: Path                    # sketch folder, relative to the repository root
    copies: dict[str, str]        # sketch-relative destination -> repository-relative source
    hand_written: frozenset[str]  # sketch-relative files that are not generated
    ino: str                      # the sketch's .ino (also hand-written)


PERF_EVAL = Sketch(
    path=Path("firmware/perf_eval_arduino"),
    copies={**SHARED,
            "src/perf_eval.hpp": str(IDF / "main/perf_eval.hpp"),
            "src/perf_eval.cpp": str(IDF / "main/perf_eval.cpp")},
    hand_written=frozenset({"perf_eval_arduino.ino", "src/arduino_config.h", "README.md"}),
    ino="perf_eval_arduino.ino",
)

DETECTOR = Sketch(
    path=Path("firmware/detector"),
    # The Arduino build switches (esp-dl source, version check) are the evaluation
    # sketch's hand-written file, shared so the two sketches cannot disagree.
    copies={**SHARED, "src/arduino_config.h": "firmware/perf_eval_arduino/src/arduino_config.h"},
    hand_written=frozenset({
        "detector.ino", "README.md",
        "src/detector_app.hpp", "src/detector_app.cpp",
        "src/detector_logic.hpp", "src/detector_logic.cpp",
        "src/web.hpp", "src/web.cpp", "src/web_page.h",
        # Host-only (the Arduino IDE compiles the sketch root and src/ only).
        "host_test/logic_cli.cpp",
    }),
    ino="detector.ino",
)

SKETCHES: tuple[Sketch, ...] = (PERF_EVAL, DETECTOR)
MARKER = "GENERATED by python -m tinyseek.deploy.arduino_sketch"


def banner(source: str) -> str:
    return (f"// {MARKER} from {source}.\n"
            "// Do not edit this copy: edit the source and regenerate.\n")


def expected(source: str, root: Path = REPO) -> str:
    text = (root / source).read_text().replace("\r\n", "\n")
    return banner(source) + text


def stale(root: Path = REPO, sketches: tuple[Sketch, ...] = SKETCHES) -> list[str]:
    """Copies (repository-relative) whose content differs from banner + source, or missing."""
    out = []
    for sk in sketches:
        for dest, source in sk.copies.items():
            path = root / sk.path / dest
            if not path.exists() or path.read_text().replace("\r\n", "\n") != expected(source, root):
                out.append((sk.path / dest).as_posix())
    return out


def orphans(root: Path = REPO, sketches: tuple[Sketch, ...] = SKETCHES) -> list[str]:
    """Generated files (repository-relative) that no longer have a source mapping."""
    found = []
    for sk in sketches:
        folder = root / sk.path
        if not folder.exists():
            continue
        for path in folder.rglob("*"):
            rel = path.relative_to(folder).as_posix()
            if path.is_file() and rel not in sk.copies and MARKER in path.read_text(errors="ignore"):
                found.append((sk.path / rel).as_posix())
    return sorted(found)


INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.MULTILINE)


def unresolved_includes(root: Path = REPO, sketches: tuple[Sketch, ...] = SKETCHES) -> list[str]:
    """Quoted includes of sketch files that do not resolve from the including file's folder.

    GCC searches the including file's own directory first; the Arduino build adds no
    include path for the sketch's src/ folder, so that is the only lookup to rely on.
    Includes of files the sketch does not contain (ESP-IDF, the core, libraries) are skipped.
    """
    bad = []
    for sk in sketches:
        folder = root / sk.path
        names = {Path(p).name for p in [*sk.copies, *sk.hand_written]}
        for rel in sorted({*sk.copies, *sk.hand_written}):
            path = folder / rel
            if not path.exists() or path.suffix not in {".c", ".cpp", ".h", ".hpp", ".ino"}:
                continue
            if rel.startswith("host_test/"):
                continue  # built by the host tests with their own include paths
            for inc in INCLUDE.findall(path.read_text()):
                if Path(inc).name in names and not (path.parent / inc).exists():
                    bad.append(f"{(sk.path / rel).as_posix()}: {inc}")
    return bad


def generate(root: Path = REPO, sketches: tuple[Sketch, ...] = SKETCHES) -> list[str]:
    """Rewrites stale copies and removes orphans; returns what it touched (repo-relative)."""
    by_path = {(sk.path / dest).as_posix(): (sk, dest) for sk in sketches for dest in sk.copies}
    written = []
    for rel in stale(root, sketches):
        sk, dest = by_path[rel]
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected(sk.copies[dest], root), newline="\n")
        written.append(rel)
    for rel in orphans(root, sketches):
        (root / rel).unlink()
        written.append(f"{rel} (removed)")
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report stale copies and exit 1 instead of writing")
    args = parser.parse_args()
    if args.check:
        problems = stale() + [f"{o} (orphan)" for o in orphans()]
        for p in problems:
            print(f"stale: {p}")
        raise SystemExit(1 if problems else 0)
    for w in generate():
        print(f"wrote {w}")
    for b in unresolved_includes():
        print(f"warning: unresolved include {b}")


if __name__ == "__main__":
    main()

"""Generate the Arduino sketch's copies of the shared firmware sources.

    python -m tinyseek.deploy.arduino_sketch          # rewrite the copies
    python -m tinyseek.deploy.arduino_sketch --check  # exit 1 if any copy is stale

The ESP-IDF project (firmware/perf_eval) is the single source of truth. The Arduino IDE
compiles only files inside the sketch folder and symlinks do not survive on Windows, so
firmware/perf_eval_arduino/src/ holds verbatim copies, each behind a "generated" banner.
Build differences live in the sources behind ``#ifdef ARDUINO``. The only hand-written
files in the sketch folder are the .ino, src/arduino_config.h and the README.
tests/test_deploy_arduino_sketch.py fails when a copy drifts from its source.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
IDF = Path("firmware/perf_eval")
CORE = IDF / "components/tinyseek_core"
SKETCH = Path("firmware/perf_eval_arduino")

# sketch path -> source path, both relative to the repository root.
COPIES: dict[str, str] = {
    "src/perf_eval.hpp": str(IDF / "main/perf_eval.hpp"),
    "src/perf_eval.cpp": str(IDF / "main/perf_eval.cpp"),
    "src/platform.hpp": str(IDF / "main/platform.hpp"),
    "src/platform.cpp": str(IDF / "main/platform.cpp"),
    "src/camera.hpp": str(IDF / "main/camera.hpp"),
    "src/camera.cpp": str(IDF / "main/camera.cpp"),
    "src/board_pins.h": "firmware/capture/board_pins.h",
    "src/tinyseek_core/preprocess.hpp": str(CORE / "include/tinyseek_core/preprocess.hpp"),
    "src/tinyseek_core/decode.hpp": str(CORE / "include/tinyseek_core/decode.hpp"),
    "src/tinyseek_core/jpeg_info.hpp": str(CORE / "include/tinyseek_core/jpeg_info.hpp"),
    "src/preprocess.cpp": str(CORE / "src/preprocess.cpp"),
    "src/decode.cpp": str(CORE / "src/decode.cpp"),
    "src/jpeg_info.cpp": str(CORE / "src/jpeg_info.cpp"),
}
HAND_WRITTEN = {"perf_eval_arduino.ino", "src/arduino_config.h", "README.md"}
MARKER = "GENERATED by python -m tinyseek.deploy.arduino_sketch"


def banner(source: str) -> str:
    return (f"// {MARKER} from {source}.\n"
            "// Do not edit this copy: edit the source and regenerate.\n")


def expected(source: str, root: Path = REPO) -> str:
    text = (root / source).read_text().replace("\r\n", "\n")
    return banner(source) + text


def stale(root: Path = REPO) -> list[str]:
    """Sketch copies whose content differs from banner + source (or that are missing)."""
    out = []
    for dest, source in COPIES.items():
        path = root / SKETCH / dest
        if not path.exists() or path.read_text().replace("\r\n", "\n") != expected(source, root):
            out.append(dest)
    return out


def orphans(root: Path = REPO) -> list[str]:
    """Generated files in the sketch that no longer have a source mapping."""
    sketch = root / SKETCH
    found = []
    for path in sketch.rglob("*"):
        rel = path.relative_to(sketch).as_posix()
        if path.is_file() and rel not in COPIES and MARKER in path.read_text(errors="ignore"):
            found.append(rel)
    return sorted(found)


INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.MULTILINE)


def unresolved_includes(root: Path = REPO) -> list[str]:
    """Quoted includes of sketch files that do not resolve from the including file's folder.

    GCC searches the including file's own directory first; the Arduino build adds no
    include path for the sketch's src/ folder, so that is the only lookup to rely on.
    Includes of files the sketch does not contain (ESP-IDF, the core, libraries) are skipped.
    """
    sketch = root / SKETCH
    names = {Path(p).name for p in [*COPIES, *HAND_WRITTEN]}
    bad = []
    for rel in [*COPIES, "src/arduino_config.h", "perf_eval_arduino.ino"]:
        path = sketch / rel
        if not path.exists():
            continue
        for inc in INCLUDE.findall(path.read_text()):
            if Path(inc).name in names and not (path.parent / inc).exists():
                bad.append(f"{rel}: {inc}")
    return bad


def generate(root: Path = REPO) -> list[str]:
    written = []
    for dest in stale(root):
        path = root / SKETCH / dest
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected(COPIES[dest], root), newline="\n")
        written.append(dest)
    for rel in orphans(root):
        (root / SKETCH / rel).unlink()
        written.append(f"{rel} (removed)")
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report stale copies and exit 1 instead of writing")
    args = parser.parse_args()
    if args.check:
        problems = stale() + [f"{o} (orphan)" for o in orphans()]
        for p in problems:
            print(f"stale: {SKETCH / p}")
        raise SystemExit(1 if problems else 0)
    for w in generate():
        print(f"wrote {SKETCH / w}")
    for b in unresolved_includes():
        print(f"warning: unresolved include {b}")


if __name__ == "__main__":
    main()
